let PGP_LANG = 'en';

function pgpSetLang(l) {
  PGP_LANG = (l === 'tr') ? 'tr' : 'en';
}

function t(key, vars) {
  const dict = PGP_I18N[PGP_LANG] || PGP_I18N.en;
  let s = dict[key] != null ? dict[key] : (PGP_I18N.en[key] != null ? PGP_I18N.en[key] : key);
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}
